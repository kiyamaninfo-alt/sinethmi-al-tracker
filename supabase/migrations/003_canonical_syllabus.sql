CREATE OR REPLACE FUNCTION public.seed_user_syllabus_from_canonical(p_user_id UUID)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_sub RECORD;
  v_unit RECORD;
  v_unit_id UUID;
  v_clean_title TEXT;
BEGIN
  FOR v_sub IN SELECT id, slug, code FROM public.subjects WHERE user_id = p_user_id LOOP
    -- Delete existing units and subunits for this subject
    DELETE FROM public.syllabus_units WHERE subject_id = v_sub.id;

    -- Insert units from canonical_syllabus matching subject code/slug
    FOR v_unit IN 
      SELECT DISTINCT unit_number, unit_name 
      FROM public.canonical_syllabus 
      WHERE UPPER(subject) = UPPER(v_sub.code) OR UPPER(subject) = UPPER(v_sub.slug)
      ORDER BY unit_number
    LOOP
      v_clean_title := regexp_replace(v_unit.unit_name, '^ඒකකය\s*\d+\s*:\s*', '');
      INSERT INTO public.syllabus_units (subject_id, unit_number, title, sinhala_title)
      VALUES (v_sub.id, v_unit.unit_number, v_clean_title, v_unit.unit_name)
      RETURNING id INTO v_unit_id;

      -- Insert subunits
      INSERT INTO public.syllabus_subunits (unit_id, sub_number, title, target_hours)
      SELECT v_unit_id, sub_lesson_code, sub_lesson_title, 4
      FROM public.canonical_syllabus
      WHERE (UPPER(subject) = UPPER(v_sub.code) OR UPPER(subject) = UPPER(v_sub.slug))
        AND unit_number = v_unit.unit_number
      ORDER BY sub_lesson_code;
    END LOOP;
  END LOOP;
END;
$$;

-- 4) Seed any existing users automatically
DO $$
DECLARE
  u RECORD;
BEGIN
  FOR u IN SELECT id FROM public.profiles LOOP
    PERFORM public.seed_user_syllabus_from_canonical(u.id);
  END LOOP;
END;
$$;